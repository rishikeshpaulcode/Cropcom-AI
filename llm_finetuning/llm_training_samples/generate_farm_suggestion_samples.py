import csv
import pandas as pd
from pydantic import BaseModel, Field
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_core.prompts import PromptTemplate

# api keys
GEMINI_API_KEY = ""

# input and output files
FARM_DATA = pd.read_csv("llm_finetuning/sample_farm_data/numerical_farm_scenarios.csv")
OUTPUT_FILE = open("llm_finetuning/llm_training_samples/generated_farm_suggestions.csv", mode="a", newline="", encoding="utf-8")
NUM_SAMPLES = 2000


# schemas
class FineTuningSample(BaseModel):
    summary: str = Field(description="Summary of the current farm and weather data in simple language.")
    instructions: str = Field(description="All the actions farmer must take on a perticular day.")

class QualityEvaluation(BaseModel):
    score: int = Field(description="Quality score of the suggested instructions from 1 to 10.")


# llms
teacher_llm = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    api_key=GEMINI_API_KEY,
    temperature=0.4
).with_structured_output(schema=FineTuningSample)

judge_llm= ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    api_key=GEMINI_API_KEY,
    temperature=0.2
).with_structured_output(schema=QualityEvaluation)


# prompts
teacher_prompt = PromptTemplate(
    template="""
        You are an experienced argultural assistant having emence domain knowledge. You are given the real time farm (crop and soil) and weather data. You task is to summarize the data in simple words then suggest the farmer a set of instructions they must follow today.\n
        Realtime farm data: 
        - Crop: {crop},
        - Growth Stage: {growth_stage},
        - Pathogen/Disease Detected: {disease_detected},
        - Soil Type: {soil_type},
        - Soil Moisture: {soil_moisture_pct}%,
        - Nitrogen (N): {npk_nitrogen_mg_kg} mg/kg,
        - Phosphorus (P): {npk_phosphorus_mg_kg} mg/kg,
        - Potassium (K): {npk_potassium_mg_kg} mg/kg,
        - Ambient Temperature: {temp_c}°C,
        - Relative Humidity: {dht11_humidity_pct}%,
        - Atmospheric Pressure: {atmospheric_pressure_hpa} hPa,
        - Solar Irradiance: {solar_irradiance_wm2} W/m²,
        - Wind Speed: {wind_speed_kmh} km/h,
        - Forecasted Rain: {forecast_rain_mm} mm

        Note: Return only plain text. No formatting or pointers needed.
    """
)

judge_prompt = PromptTemplate(
    template="""
        You are an expert agricultural auditor and experienced agriculture domain expert.
        Your task is to strictly evaluate the acctionabe suggestions generated by a smart farming assistant.
        Assign a 'score' between 0 (completely inaccurate/dangerous) and 10 (perfectly accurate and actionable).

        Realtime farm data: 
        - Crop: {crop},
        - Growth Stage: {growth_stage},
        - Pathogen/Disease Detected: {disease_detected},
        - Soil Type: {soil_type},
        - Soil Moisture: {soil_moisture_pct}%,
        - Nitrogen (N): {npk_nitrogen_mg_kg} mg/kg,
        - Phosphorus (P): {npk_phosphorus_mg_kg} mg/kg,
        - Potassium (K): {npk_potassium_mg_kg} mg/kg,
        - Ambient Temperature: {temp_c}°C,
        - Relative Humidity: {dht11_humidity_pct}%,
        - Atmospheric Pressure: {atmospheric_pressure_hpa} hPa,
        - Solar Irradiance: {solar_irradiance_wm2} W/m²,
        - Wind Speed: {wind_speed_kmh} km/h,
        - Forecasted Rain: {forecast_rain_mm} mm

        Instructions provided:
        {instructions}
    """
)


# generate training corpus
if __name__ == "__main__":
    csv_writer = csv.writer(OUTPUT_FILE)
    i = 14

    while i < NUM_SAMPLES:
        try:
            curr_farm_data = {
                "crop": FARM_DATA.loc[i, "crop"],
                "growth_stage": FARM_DATA.loc[i, "growth_stage"],
                "disease_detected": FARM_DATA.loc[i, "disease_detected"],
                "soil_type": FARM_DATA.loc[i, "soil_type"],
                "soil_moisture_pct": FARM_DATA.loc[i, "soil_moisture_pct"],
                "npk_nitrogen_mg_kg": FARM_DATA.loc[i, "npk_nitrogen_mg_kg"],
                "npk_phosphorus_mg_kg": FARM_DATA.loc[i, "npk_phosphorus_mg_kg"],
                "npk_potassium_mg_kg": FARM_DATA.loc[i, "npk_potassium_mg_kg"],
                "temp_c": FARM_DATA.loc[i, "temp_c"],
                "dht11_humidity_pct": FARM_DATA.loc[i, "dht11_humidity_pct"],
                "atmospheric_pressure_hpa": FARM_DATA.loc[i, "atmospheric_pressure_hpa"],
                "solar_irradiance_wm2": FARM_DATA.loc[i, "solar_irradiance_wm2"],
                "wind_speed_kmh": FARM_DATA.loc[i, "wind_speed_kmh"],
                "forecast_rain_mm": FARM_DATA.loc[i, "forecast_rain_mm"]
            }

            # generate sample suggestions using teacher llm
            print(f"Generating suggestion for sample: {i}", end=" ")
            formatted_teacher_prompt = teacher_prompt.invoke(curr_farm_data)
            teacher_response = teacher_llm.invoke(formatted_teacher_prompt)

            # validate generated suggestions using judge llm
            formatted_judge_prompt = judge_prompt.invoke(curr_farm_data | {"instructions": teacher_response.instructions})
            judge_verdict = judge_llm.invoke(formatted_judge_prompt)

            # regenerate suggestion if quality criteria not satisfied
            if judge_verdict.score < 6:
                print("Quality check fail. Regenerating...")
                continue

            # store generated suggestion into csv file if quality criteria satisfied
            print("Pass! Writing...", end=" ")
            csv_writer.writerow([i, teacher_response.summary, teacher_response.instructions])

            print("Written succesfully.")
            i += 1
        
        except Exception as e:
            print("\nError Encountered.")
            print(e)
            break
    
    OUTPUT_FILE.close()
    print(f"\nSuccessfully saved {i} samples to {OUTPUT_FILE}")
